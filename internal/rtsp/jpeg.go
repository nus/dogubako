package rtsp

import (
	"bytes"
	"fmt"
)

// JPEG over RTP (RFC 2435), plus a raw-JPEG fallback used by some cameras.
type jpegDepacketizer struct {
	buf     []byte
	raw     bool
	typ     byte
	q       byte
	w, h    int
	dri     uint16
	qtables []byte
	off     int
}

func (d *jpegDepacketizer) Reset() {
	d.buf = d.buf[:0]
	d.raw = false
	d.off = 0
	d.qtables = nil
}

// Push appends one RTP JPEG payload. A complete frame is returned when marker is set.
func (d *jpegDepacketizer) Push(payload []byte, marker bool) ([]byte, error) {
	if len(payload) < 8 {
		if marker {
			d.Reset()
		}
		return nil, fmt.Errorf("jpeg: short rtp payload")
	}
	fragOff := int(payload[1])<<16 | int(payload[2])<<8 | int(payload[3])
	typ := payload[4]
	q := payload[5]
	w := int(payload[6]) * 8
	h := int(payload[7]) * 8
	rest := payload[8:]

	if typ >= 64 && typ < 128 {
		if len(rest) < 4 {
			return nil, fmt.Errorf("jpeg: short restart header")
		}
		d.dri = uint16(rest[0])<<8 | uint16(rest[1])
		rest = rest[4:]
	} else {
		d.dri = 0
	}

	if fragOff == 0 {
		d.Reset()
		d.typ = typ & 0x3f
		d.q = q
		d.w, d.h = w, h
		if q >= 128 {
			tables, n, err := readQTables(rest)
			if err != nil {
				return nil, err
			}
			d.qtables = tables
			rest = rest[n:]
		}
		if len(rest) >= 2 && rest[0] == 0xff && rest[1] == 0xd8 {
			d.raw = true
		}
	} else if d.off != fragOff {
		d.Reset()
		return nil, nil
	}

	d.buf = append(d.buf, rest...)
	d.off = fragOff + len(rest)
	if !marker {
		return nil, nil
	}
	frame := d.finish()
	d.Reset()
	return frame, nil
}

func (d *jpegDepacketizer) finish() []byte {
	if len(d.buf) == 0 {
		return nil
	}
	if d.raw || (len(d.buf) >= 2 && d.buf[0] == 0xff && d.buf[1] == 0xd8) {
		out := append([]byte(nil), d.buf...)
		if !bytes.HasSuffix(out, []byte{0xff, 0xd9}) {
			out = append(out, 0xff, 0xd9)
		}
		return out
	}
	tables := d.qtables
	if len(tables) == 0 {
		tables = defaultQTables(int(d.q))
	}
	return makeJPEG(d.w, d.h, d.typ, d.dri, tables, d.buf)
}

func readQTables(b []byte) ([]byte, int, error) {
	if len(b) < 4 {
		return nil, 0, fmt.Errorf("jpeg: short qtable header")
	}
	length := int(b[2])<<8 | int(b[3])
	n := 4 + length
	if length <= 0 || n > len(b) {
		return nil, 0, fmt.Errorf("jpeg: bad qtable length")
	}
	return append([]byte(nil), b[4:n]...), n, nil
}

func defaultQTables(q int) []byte {
	if q < 1 {
		q = 1
	}
	if q > 99 {
		q = 99
	}
	scale := 200 - 2*q
	if q < 50 {
		scale = 5000 / q
	}
	out := make([]byte, 128)
	for i := 0; i < 64; i++ {
		l := (int(jpegLumaQuant[i])*scale + 50) / 100
		c := (int(jpegChromaQuant[i])*scale + 50) / 100
		out[i] = clampQuant(l)
		out[64+i] = clampQuant(c)
	}
	return out
}

func clampQuant(v int) byte {
	if v < 1 {
		return 1
	}
	if v > 255 {
		return 255
	}
	return byte(v)
}

func makeJPEG(width, height int, typ byte, dri uint16, qtables, scan []byte) []byte {
	if width <= 0 || height <= 0 || len(scan) == 0 {
		return nil
	}
	luma := qtables
	chroma := qtables
	if len(qtables) >= 128 {
		luma = qtables[:64]
		chroma = qtables[64:128]
	} else if len(qtables) < 64 {
		qtables = defaultQTables(80)
		luma = qtables[:64]
		chroma = qtables[64:]
	}
	var buf bytes.Buffer
	buf.Grow(1024 + len(scan))
	buf.Write([]byte{0xff, 0xd8}) // SOI
	buf.Write([]byte{0xff, 0xdb, 0x00, 0x43, 0x00})
	buf.Write(luma[:64])
	buf.Write([]byte{0xff, 0xdb, 0x00, 0x43, 0x01})
	buf.Write(chroma[:64])
	writeDHT(&buf)
	if dri > 0 {
		buf.Write([]byte{0xff, 0xdd, 0x00, 0x04, byte(dri >> 8), byte(dri)})
	}
	// SOF0
	var hvY byte = 0x21 // 4:2:2
	if typ == 1 {
		hvY = 0x22 // 4:2:0
	}
	sof := []byte{
		0xff, 0xc0, 0x00, 0x11, 0x08,
		byte(height >> 8), byte(height),
		byte(width >> 8), byte(width),
		0x03,
		0x01, hvY, 0x00,
		0x02, 0x11, 0x01,
		0x03, 0x11, 0x01,
	}
	buf.Write(sof)
	// SOS
	buf.Write([]byte{
		0xff, 0xda, 0x00, 0x0c, 0x03,
		0x01, 0x00,
		0x02, 0x11,
		0x03, 0x11,
		0x00, 0x3f, 0x00,
	})
	buf.Write(scan)
	if !bytes.HasSuffix(scan, []byte{0xff, 0xd9}) {
		buf.Write([]byte{0xff, 0xd9})
	}
	return buf.Bytes()
}

func writeDHT(buf *bytes.Buffer) {
	// RFC 2435 Appendix B / JPEG spec typical Huffman tables.
	buf.Write([]byte{0xff, 0xc4, 0x00, 0x1f, 0x00})
	buf.Write(jpegLumDCBits)
	buf.Write(jpegLumDCVal)
	buf.Write([]byte{0xff, 0xc4, 0x00, 0xb5, 0x10})
	buf.Write(jpegLumACBits)
	buf.Write(jpegLumACVal)
	buf.Write([]byte{0xff, 0xc4, 0x00, 0x1f, 0x01})
	buf.Write(jpegChrDCBits)
	buf.Write(jpegChrDCVal)
	buf.Write([]byte{0xff, 0xc4, 0x00, 0xb5, 0x11})
	buf.Write(jpegChrACBits)
	buf.Write(jpegChrACVal)
}

